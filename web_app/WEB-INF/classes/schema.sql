CREATE SEQUENCE IF NOT EXISTS bookingid START WITH 21;
CREATE SEQUENCE IF NOT EXISTS transactionid START WITH 21;

CREATE TABLE IF NOT EXISTS ACCOUNTCATEGORY (
    ACCOUNTCATEGORY VARCHAR(40)
);

CREATE TABLE IF NOT EXISTS ACCOUNTDETALIS (
    ACCNUMBER VARCHAR(40) NOT NULL PRIMARY KEY,
    ACCOUNTHOLDERNAME VARCHAR(40),
    AVAILABLEBALENCE VARCHAR(40),
    MINIMUMBALENCE VARCHAR(40),
    PINNUMBER VARCHAR(40)
);

CREATE TABLE IF NOT EXISTS USERDETALIS (
    USERID VARCHAR(40) NOT NULL PRIMARY KEY,
    FIRSTNAME VARCHAR(40),
    LASTNAME VARCHAR(40),
    GENDER VARCHAR(40),
    DOB VARCHAR(40),
    PASSWORD VARCHAR(40),
    CONTACTNUMBER VARCHAR(40),
    ADDRESS VARCHAR(4000) NOT NULL,
    CITYID VARCHAR(40)
);

CREATE TABLE IF NOT EXISTS BOOKING (
    BOOKINGID VARCHAR(40) NOT NULL PRIMARY KEY,
    NOOFPEOPLE VARCHAR(40),
    BOOKIGDATE VARCHAR(40),
    COST VARCHAR(40),
    FID VARCHAR(40),
    USERID VARCHAR(4000),
    STATUS VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS PLACES (
    PLACEID VARCHAR(40) NOT NULL PRIMARY KEY,
    PLACENAME VARCHAR(40)
);

CREATE TABLE IF NOT EXISTS PLACES_PLACES (
    SOURCE VARCHAR(40) NOT NULL,
    DEST VARCHAR(40) NOT NULL,
    PRIMARY KEY (SOURCE, DEST)
);

CREATE TABLE IF NOT EXISTS COUNTRY (
    COUNTRYID VARCHAR(40) NOT NULL PRIMARY KEY,
    COUNTRYNAME VARCHAR(40)
);

CREATE TABLE IF NOT EXISTS STATE (
    STATEID VARCHAR(40) NOT NULL PRIMARY KEY,
    STATENAME VARCHAR(40),
    COUNTRYID VARCHAR(40)
);

CREATE TABLE IF NOT EXISTS CITY (
    CITYID VARCHAR(40) NOT NULL PRIMARY KEY,
    CITYNAME VARCHAR(40),
    STATEID VARCHAR(40)
);

CREATE TABLE IF NOT EXISTS CLASS (
    CLASSID VARCHAR(40) NOT NULL PRIMARY KEY,
    CLASSNAME VARCHAR(40)
);

CREATE TABLE IF NOT EXISTS FLIGHTCATEGORY (
    FLIGHTCATID VARCHAR(40) NOT NULL PRIMARY KEY,
    FLIGHTCATEGORY VARCHAR(40)
);

CREATE TABLE IF NOT EXISTS FLIGHTDETALIS (
    FID VARCHAR(40) NOT NULL PRIMARY KEY,
    FNAME VARCHAR(40),
    FLIGHTCATID VARCHAR(40),
    CLASSID VARCHAR(40),
    SOURCE VARCHAR(40),
    DEST VARCHAR(40),
    COST VARCHAR(4000)
);

CREATE TABLE IF NOT EXISTS TRANSACTION (
    TRANSACTIONID VARCHAR(40) NOT NULL PRIMARY KEY,
    DATEOFTRANSACTION VARCHAR(40),
    TRANSFFEREDAMOUNT VARCHAR(40),
    TOACCOUNT VARCHAR(40),
    ACCOUNTNUMBER VARCHAR(40),
    BOOKINGID VARCHAR(40)
);

-- Foreign Key Constraints
ALTER TABLE PLACES_PLACES ADD CONSTRAINT IF NOT EXISTS ONETOMANY FOREIGN KEY (SOURCE) REFERENCES PLACES (PLACEID);
ALTER TABLE PLACES_PLACES ADD CONSTRAINT IF NOT EXISTS PLACES_PLACES_PLACES FOREIGN KEY (DEST) REFERENCES PLACES (PLACEID);
ALTER TABLE CITY ADD CONSTRAINT IF NOT EXISTS STATE_CITY FOREIGN KEY (STATEID) REFERENCES STATE (STATEID);
ALTER TABLE TRANSACTION ADD CONSTRAINT IF NOT EXISTS ACCOUNTDETALIS_TRANSACTION FOREIGN KEY (ACCOUNTNUMBER) REFERENCES ACCOUNTDETALIS (ACCNUMBER);
ALTER TABLE TRANSACTION ADD CONSTRAINT IF NOT EXISTS BOOKING_TRANSACTION FOREIGN KEY (BOOKINGID) REFERENCES BOOKING (BOOKINGID);
ALTER TABLE BOOKING ADD CONSTRAINT IF NOT EXISTS BOOKING_CON FOREIGN KEY (USERID) REFERENCES USERDETALIS (USERID);
ALTER TABLE STATE ADD CONSTRAINT IF NOT EXISTS COUNTRY_STATE FOREIGN KEY (COUNTRYID) REFERENCES COUNTRY (COUNTRYID);
ALTER TABLE BOOKING ADD CONSTRAINT IF NOT EXISTS FLIGHTDETALIS_BOOKING FOREIGN KEY (FID) REFERENCES FLIGHTDETALIS (FID);
ALTER TABLE USERDETALIS ADD CONSTRAINT IF NOT EXISTS CITY_USERDETALIS FOREIGN KEY (CITYID) REFERENCES CITY (CITYID);
ALTER TABLE FLIGHTDETALIS ADD CONSTRAINT IF NOT EXISTS FLIGHTCATEGORY_FLIGHTDETALIS FOREIGN KEY (FLIGHTCATID) REFERENCES FLIGHTCATEGORY (FLIGHTCATID);
ALTER TABLE FLIGHTDETALIS ADD CONSTRAINT IF NOT EXISTS CLASS_FLIGHTDETALIS FOREIGN KEY (CLASSID) REFERENCES CLASS (CLASSID);
ALTER TABLE FLIGHTDETALIS ADD CONSTRAINT IF NOT EXISTS PLACES_PLACES_FLIGHTDETALIS FOREIGN KEY (SOURCE, DEST) REFERENCES PLACES_PLACES (SOURCE, DEST);

